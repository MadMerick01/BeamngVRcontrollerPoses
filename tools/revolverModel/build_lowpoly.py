"""Builds the low-poly revolver that vrPistol draws with the debug drawer.

The textured revolver is a scene object, and BeamNG redraws mod-placed scene
objects late, so it trails the car at speed. Triangles drawn with the debug
drawer are painted fresh every frame (like the laser), so this simplified copy
stays locked to the hand. It reads the shapes in mod/art/shapes/vrrevolver,
decimates each part, takes one colour per material (the average of its texture
where it has one) and writes mod/lua/ge/extensions/vrPistolMesh.lua.

    pip install pillow numpy
    python tools/revolverModel/build_lowpoly.py
"""
import json
import re
import xml.etree.ElementTree as ET
from pathlib import Path

import numpy as np
from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
SHAPES = ROOT / "mod/art/shapes/vrrevolver"
OUT = ROOT / "mod/lua/ge/extensions/vrPistolMesh.lua"
NS = {"c": "http://www.collada.org/2005/11/COLLADASchema"}

# Triangle budget per part; about 1,500 in all keeps drawing well under 1 ms.
BUDGET = {"frame": 900, "cylinder": 420, "hammer": 110, "trigger": 70, "flash": 20}


def material_colours():
    mats = json.loads((SHAPES / "main.materials.json").read_text())
    colours = {}
    for name, m in mats.items():
        stage = m["Stages"][0]
        rgb = np.array(stage.get("baseColorFactor", [0.8, 0.8, 0.8, 1])[:3], dtype=float)
        tex = stage.get("baseColorMap")
        if tex:
            img = np.asarray(Image.open(SHAPES / Path(tex).name).convert("RGB"), dtype=float) / 255
            rgb = rgb * img.reshape(-1, 3).mean(0) if "baseColorFactor" in stage else img.reshape(-1, 3).mean(0)
        colours[name] = [int(round(min(1, c) * 255)) for c in rgb]
    return colours


def read_part(path):
    """Yields (material, vertices Nx3, faces Mx3) for every triangle group."""
    tree = ET.parse(path)
    for geom in tree.getroot().iter(f"{{{NS['c']}}}geometry"):
        mesh = geom.find("c:mesh", NS)
        sources = {s.get("id"): s for s in mesh.findall("c:source", NS)}
        verts = mesh.find("c:vertices", NS)
        pos_id = verts.find("c:input[@semantic='POSITION']", NS).get("source")[1:]
        pos = np.array(sources[pos_id].find("c:float_array", NS).text.split(), dtype=float).reshape(-1, 3)
        for tris in mesh.findall("c:triangles", NS):
            stride = max(int(i.get("offset", 0)) for i in tris.findall("c:input", NS)) + 1
            vo = int(tris.find("c:input[@semantic='VERTEX']", NS).get("offset", 0))
            p = np.array(tris.find("c:p", NS).text.split(), dtype=int).reshape(-1, stride)[:, vo]
            yield tris.get("material"), pos, p.reshape(-1, 3)


def cluster(verts, faces, cell):
    """Vertex clustering: snap corners to a grid, keep the triangles that survive."""
    keys = np.floor(verts / cell).astype(np.int64)
    uniq, inverse = np.unique(keys, axis=0, return_inverse=True)
    inverse = inverse.reshape(-1)
    sums = np.zeros((len(uniq), 3))
    np.add.at(sums, inverse, verts)
    centres = sums / np.bincount(inverse, minlength=len(uniq))[:, None]
    f = inverse[faces]
    f = f[(f[:, 0] != f[:, 1]) & (f[:, 1] != f[:, 2]) & (f[:, 0] != f[:, 2])]
    # Drop duplicates, including the same triangle wound the other way.
    _, keep = np.unique(np.sort(f, axis=1), axis=0, return_index=True)
    return centres, f[np.sort(keep)]


def decimate(verts, faces, target):
    """Largest detail (smallest grid cell) that fits the triangle budget."""
    if len(faces) <= target:
        return verts, faces
    lo, hi = 1e-4, 0.05
    best = cluster(verts, faces, hi)
    for _ in range(24):
        mid = (lo * hi) ** 0.5
        v, f = cluster(verts, faces, mid)
        if len(f) <= target:
            best, hi = (v, f), mid
        else:
            lo = mid
    return best


def main():
    colours = material_colours()
    parts = {}
    for name, budget in BUDGET.items():
        groups = list(read_part(SHAPES / f"{name}.dae"))
        total = sum(len(f) for _, _, f in groups)
        tris, cols = [], []
        for mat, verts, faces in groups:
            target = max(min(len(faces), 12), int(round(budget * len(faces) / total)))
            v, f = decimate(verts, faces, target)
            colour = colours.get(mat, [200, 200, 200])
            for a, b, c in f:
                tris.extend(np.concatenate([v[a], v[b], v[c]]).tolist())
                cols.extend(colour)
        parts[name] = (tris, cols)
        print(f"{name}: {total} -> {len(cols) // 3} triangles")

    def nums(xs, fmt):
        return ",".join(fmt % x for x in xs)

    lines = [
        "-- Generated by tools/revolverModel/build_lowpoly.py; do not edit.",
        "-- Low-poly revolver for the debug drawer: per part, flat triangle corners",
        "-- (x, y, z in the part's own space: +Y along the barrel, +Z up) and one",
        "-- RGB colour per triangle.",
        "return {",
    ]
    for name, (tris, cols) in parts.items():
        lines.append(f"  {name} = {{")
        lines.append(f"    tris = {{{nums(tris, '%.5f')}}},")
        lines.append(f"    colours = {{{nums(cols, '%d')}}},")
        lines.append("  },")
    lines.append("}")
    OUT.write_text("\n".join(lines) + "\n")
    print("wrote", OUT.relative_to(ROOT), f"({OUT.stat().st_size // 1024} KB)")


if __name__ == "__main__":
    main()
